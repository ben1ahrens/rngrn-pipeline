# 3. run-index wrapper
# ======================================================================================
def _latent_diagnostics(latent_fields: Any, observed_idx: Sequence[int],
                        extra_idx: Sequence[int], n_model: int) -> dict:
    """Spatial-contrast diagnostics for the spare species' inferred latent field.

    DIAGNOSTIC ONLY — deliberately not folded into `spare_species_inert`, because a
    contrast cut has not been calibrated. `latent_fields` rows map to the unobserved
    model indices in ascending order (the convention in losses.terms.stationarity_
    residual and recover.recover). Returns nan fields with a stated reason when no
    latent field was inferred (m == N) rather than inventing a value.
    """
    nan = float("nan")
    if latent_fields is None:
        return dict(latent_extra_std_max=nan, latent_extra_absmean_max=nan,
                    latent_extra_rel_contrast=nan,
                    latent_status="absent: no latent fields (m == N or not returned)")
    lat = np.asarray(latent_fields, dtype=float)
    lat_idx = [i for i in range(n_model) if i not in tuple(observed_idx)]
    if lat.ndim != 3 or lat.shape[0] != len(lat_idx):
        raise ValueError(
            f"latent_fields has shape {lat.shape}, expected ({len(lat_idx)}, H, W) for "
            f"unobserved model indices {lat_idx}.")
    rows = [lat_idx.index(e) for e in extra_idx]
    if not rows:
        return dict(latent_extra_std_max=nan, latent_extra_absmean_max=nan,
                    latent_extra_rel_contrast=nan,
                    latent_status="not applicable: no spare species")
    block = lat[rows]
    std = float(np.max([float(np.std(block[r])) for r in range(block.shape[0])]))
    absmean = float(np.max([abs(float(np.mean(block[r]))) for r in range(block.shape[0])]))
    rel = std / absmean if absmean > 0.0 else nan
    return dict(latent_extra_std_max=std, latent_extra_absmean_max=absmean,
                latent_extra_rel_contrast=rel,
                latent_status=("ok" if absmean > 0.0 else
                               "rel_contrast undefined: latent field mean is zero"))


def overparam_report(
    result: Any,
    answer_key: Any,
    observed_idx: Iterable[int],
    coupling_threshold: float = DEFAULT_COUPLING_THRESHOLD,
    threshold_mode: str = "relative",
    sign_zero_tol: float = DEFAULT_SIGN_ZERO_TOL,
    require_true_J: bool = True,
) -> dict:
    """One flat metric row for an over-parameterised run (Experiment B). SCAFFOLD.

    Convenience wrapper: derives J_rec / D_rec from the RecoveryResult exactly as
    validate.score_recovery does (``result.model.jacobian(torch.as_tensor(
    result.xstar), create_graph=False)`` and ``result.model.D``), reads n_true and J
    from the AnswerKey, and merges `spurious_species_metrics`,
    `observed_block_agreement`, and latent diagnostics into ONE flat dict.

    All values are scalars, bools, None, or strings — no nested dicts — so a row can go
    straight into the sqlite/jsonl run index. Both ``n_true`` and ``n_model`` are always
    present so a downstream table can never silently compare an N=2-truth run against
    an N=3-truth run.

    torch is imported inside this function, not at module scope, so the two pure-matrix
    metric functions above remain importable without torch. NOTE for bare scripts: this
    sandbox needs KMP_AFFINITY=disabled and OMP_NUM_THREADS=1 exported BEFORE the first
    torch import (tests/conftest.py does it for pytest).

    Parameters
    ----------
    result : RecoveryResult
        Needs ``.model`` (with ``.jacobian`` and ``.D``), ``.xstar``, and optionally
        ``.latent_fields``.
    answer_key : AnswerKey
        Needs ``.n_species_true`` and ``.J``. SCORING SIDE — see module docstring.
    observed_idx : sequence of int
        As for the two functions above.
    coupling_threshold, threshold_mode
        Forwarded to `spurious_species_metrics`; the default 0.05 relative cut is an
        UNCALIBRATED starting point, and the realised cut is echoed in the row.
    sign_zero_tol
        Forwarded to `observed_block_agreement`.
    require_true_J : bool, default True
        With True (fail loud), a missing or mis-shaped ``answer_key.J`` raises. With
        False, the observed-block fields are omitted and ``block_status`` records why —
        use it only for datasets that genuinely ship no Jacobian.

    Returns
    -------
    dict
        Keys from `spurious_species_metrics`, plus `observed_block_agreement` keys
        (when scored), plus latent_* diagnostics, plus:
        overparam_status : str, a human-readable one-liner
        block_status     : str, "scored" or the reason it was skipped
        n_model_from_result : int, N read off the recovered model
        loss             : float, result.loss (carried through for the index)

    Raises
    ------
    ValueError
        On a missing/mis-shaped answer key (when require_true_J), an
        ``answer_key.J`` whose size disagrees with ``answer_key.n_species_true`` (the
        exact mismatch that must never be silently NaN'd), or anything the two metric
        functions reject.
    AttributeError
        If ``result`` or ``answer_key`` lacks a required field — a caller wiring bug
        that should surface, not be defaulted away.
    """
    import torch  # local import: keeps the pure-matrix metrics torch-free

    for attr in ("model", "xstar"):
        if not hasattr(result, attr):
            raise AttributeError(f"result has no '{attr}': not a RecoveryResult.")
    if not hasattr(answer_key, "n_species_true"):
        raise AttributeError("answer_key has no 'n_species_true': not an AnswerKey.")

    J_rec = result.model.jacobian(
        torch.as_tensor(np.asarray(result.xstar, dtype=float)),
        create_graph=False).detach().numpy()
    D_rec = result.model.D.detach().numpy()
    n_model = int(np.asarray(J_rec).shape[0])
    n_true = int(answer_key.n_species_true)
    obs = _as_index_tuple(observed_idx, n_model)

    row = spurious_species_metrics(
        J_rec, D_rec, obs, n_true,
        coupling_threshold=coupling_threshold, threshold_mode=threshold_mode)
    row["n_model_from_result"] = n_model
    row["overparam_status"] = (
        f"over-parameterised: model N={n_model} vs truth n_true={n_true} "
        f"({row['n_extra']} spare)" if n_model > n_true else
        f"exactly parameterised: model N={n_model} == truth n_true={n_true}; "
        "spare-species criterion undefined")

    J_true = getattr(answer_key, "J", None)
    if J_true is None:
        if require_true_J:
            raise ValueError(
                "answer_key.J is None: the observed-block half of Experiment B cannot "
                "be scored without a true Jacobian. Pass require_true_J=False to record "
                "the row without it.")
        row["block_status"] = "skipped: answer_key.J is None"
    else:
        T = np.asarray(J_true, dtype=float)
        if T.ndim != 2 or T.shape[0] != T.shape[1] or T.shape[0] != n_true:
            raise ValueError(
                f"answer_key.J has shape {T.shape} but answer_key.n_species_true="
                f"{n_true}: the answer key is internally inconsistent. Refusing to "
                "score (this is the mismatch that must never become a silent NaN).")
        row.update(observed_block_agreement(J_rec, T, obs, sign_zero_tol=sign_zero_tol))
        row["block_status"] = "scored"

    # Same identification as spurious_species_metrics: with n_extra > 0 validated there,
    # the spare indices are exactly the unobserved ones.
    unobserved = tuple(i for i in range(n_model) if i not in obs)
    extra_idx = unobserved if row["n_extra"] else ()
    row.update(_latent_diagnostics(getattr(result, "latent_fields", None), obs,
                                   extra_idx, n_model))
    row["loss"] = float(result.loss) if hasattr(result, "loss") else float("nan")

    bad = {k: v for k, v in row.items()
           if not isinstance(v, (int, float, bool, str, type(None)))}
    if bad:
        raise ValueError(
            f"overparam_report produced non-flat values for keys {sorted(bad)}; the run "
            "index accepts only scalars/bools/strings.")
    return row
